"""장소 유형(카카오 카테고리)별 체류시간 추천값(분)."""
from __future__ import annotations

DEFAULT_STAY_MIN = 60

# (키워드, 분) — 위에서부터 먼저 맞는 항목을 씁니다. 카카오 카테고리는 "음식점 > 카페 > 커피전문점" 형태입니다.
_RULES: tuple[tuple[tuple[str, ...], int], ...] = (
    (("카페", "커피", "디저트", "베이커리", "제과"), 60),
    (("술집", "주점", "바(BAR)", "호프", "이자카야"), 90),
    (("음식점", "식당", "맛집", "한식", "양식", "일식", "중식", "분식", "뷔페"), 80),
    (("박물관", "미술관", "전시", "갤러리", "과학관", "기념관"), 120),
    (("테마파크", "놀이공원", "워터파크", "아쿠아리움", "동물원", "식물원"), 180),
    (("영화관", "공연", "극장", "콘서트"), 150),
    (("공원", "산책", "해변", "해수욕장", "호수", "수목원"), 90),
    (("관광", "명소", "궁", "사찰", "전망", "타워", "문화재"), 90),
    (("쇼핑", "백화점", "아울렛", "마트", "시장"), 90),
    (("서점", "도서관"), 60),
)


def recommend_stay(category: str | None) -> int:
    """카테고리 문자열에서 추천 체류시간(분)을 돌려줍니다. 맞는 규칙이 없으면 60분."""
    if category:
        for keywords, minutes in _RULES:
            if any(k in category for k in keywords):
                return minutes
    return DEFAULT_STAY_MIN
